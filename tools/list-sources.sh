#!/usr/bin/env bash
# Writes SOURCES.md: every file in the pack, where it comes from, and which
# Minecraft versions load it. Run it after changing the pack's contents.
set -euo pipefail
cd "$(dirname "$0")/.."

command -v jq >/dev/null || { echo "error: 'jq' is not installed (sudo apt install jq)" >&2; exit 1; }

# Pack format -> Minecraft version names, for the folders' version ranges.
versions_for() {
  local min=$1 max=$2 out=() f name
  for pair in "63 1.21.6" "64 1.21.7-1.21.8" "69 1.21.9-1.21.10" "75 1.21.11" "84 26.1" "88 26.2" "97 26.3"; do
    f=${pair%% *}; name=${pair#* }
    if [ "$f" -ge "$min" ] && [ "$f" -le "$max" ]; then out+=("$name"); fi
  done
  local first=${out[0]} last=${out[${#out[@]}-1]}
  first=${first%%-*}; last=${last##*-}
  if [ "$first" = "$last" ]; then echo "$first"; else echo "$first - $last"; fi
}

source_of() {
  case "$1" in
    assets|fog_*|sodium_*) echo "Rewind Edition: fog (based on Classic Fog by sydist)" ;;
    vanillatweaks*) echo "Vanilla Tweaks" ;;
    programmer_art_plus*) echo "Programmer Art+ by Crackers0106 (CC BY 4.0)" ;;
    *) echo "Rewind Edition" ;;
  esac
}

out=SOURCES.md
{
  echo "# What's in the pack and where it comes from"
  echo
  echo "Generated by \`tools/list-sources.sh\` - don't edit by hand."
  echo
  echo "Where Programmer Art+ and Vanilla Tweaks both have a texture, Programmer Art+'s is used, except for the Classic Panorama and Old Water from Vanilla Tweaks (see \`tools/programmer-art-plus-exclude.txt\`). Vanilla Tweaks files that Programmer Art+ replaces are not included."
  echo
  echo "## Summary"
  echo
  echo "| Folder | Comes from | Loads on Minecraft | Files |"
  echo "| --- | --- | --- | --- |"
  echo "| (root) | Rewind Edition | all | $(find . -maxdepth 1 -type f \( -name pack.mcmeta -o -name pack.png -o -name credits.txt -o -name LICENSE.md \) | wc -l) + licences |"
  echo "| \`assets/\` | $(source_of assets) | all | $(find assets -type f | wc -l) |"
  while IFS=' ' read -r dir min max; do
    echo "| \`$dir/\` | $(source_of "$dir") | $(versions_for "$min" "$max") | $(find "$dir" -type f | wc -l) |"
  done < <(jq -r '.overlays.entries[] | "\(.directory) \(.min_format) \(.max_format)"' pack.mcmeta)
  echo
  echo "## Root files"
  echo
  echo "- \`pack.mcmeta\`, \`pack.png\` (pack icon): Rewind Edition"
  echo "- \`credits.txt\`, \`LICENSE.md\`, \`licenses/\`: credits and licences"
  echo

  list_folder() {
    local dir=$1 title=$2
    echo "## \`$dir/\`: $title"
    echo
    # Group files by their folder, and list the file names in each.
    (cd "$dir" && find . -type f | sed 's|^\./||' | sort) | awk -F/ '
      {
        file = $NF
        path = $0; sub("/" file "$", "", path); if (path == $0) path = "."
        if (path != last) { if (last != "") printf "\n\n"; printf "**%s/** (%d)\n\n", path, 0; last = path; first = 1 }
        printf "%s`%s`", (first ? "" : ", "), file; first = 0
      }
      END { printf "\n\n" }' | awk '
      # Fill in the per-folder file counts (computed on a second pass).
      /^\*\*/ { header = $0; getline blank; getline files; n = gsub(/`, `/, "`, `", files) + 1; sub(/\(0\)/, "(" n ")", header); print header; print blank; print files; next }
      { print }'
  }

  list_folder assets "$(source_of assets), all versions"
  while IFS=' ' read -r dir min max; do
    list_folder "$dir" "$(source_of "$dir"), Minecraft $(versions_for "$min" "$max")"
  done < <(jq -r '.overlays.entries[] | "\(.directory) \(.min_format) \(.max_format)"' pack.mcmeta)
} > "$out"

echo "Wrote $out ($(grep -c '^\*\*' "$out") folders listed)"
